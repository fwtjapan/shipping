def lookup(zipcode):
    """3 碼 zip → '縣市區'（查不到回 None）。"""
    if not zipcode:
        return None
    z = str(zipcode).strip()[:3]
    return TW_ZIP.get(z)


def split_county_district(full):
    """'嘉義市西區' → ('嘉義市','西區')；'新竹市' → ('新竹市','')；'宜蘭縣宜蘭市' → ('宜蘭縣','宜蘭市')。"""
    import re
    m = re.match(r'^(.+?[縣市])(.*)$', full or "")
    if not m:
        return full or "", ""
    return m.group(1), m.group(2)


def is_address_complete(address):
    """判斷地址是否含「縣市 + 區級」。只有市無區（如『嘉義市…』缺西區）視為不完整。"""
    import re
    a = (address or "").strip()
    if len(a) < 6:
        return False
    if not re.search(r'[縣市]', a):
        return False
    if re.search(r'[區鄉鎮]', a):     # 有區/鄉/鎮
        return True
    if re.search(r'縣.{0,6}市', a):    # 縣轄市（頭份市、竹北市…）
        return True
    return False


def compose_full_address(province, city, address1, address2, zipcode):
    """把 Shopify 拆開的地址欄組成完整地址，並用 zip 反查補齊缺的縣市/區。
    查不到 zip 就維持原樣（不亂補）。回傳 (完整地址, 是否有補).
    """
    raw = "".join(x.strip() for x in [province or "", city or "", address1 or "", address2 or ""] if x and x.strip())
    full = lookup(zipcode)
    if not full:
        return raw, False
    if full in raw:            # 已完整
        return raw, False
    county, dist = split_county_district(full)
    # raw 已含縣市 → 只補區
    if county and raw.startswith(county):
        rest = raw[len(county):]
        if dist and rest and not rest.startswith(dist):
            return county + dist + rest, True
        return raw, False
    # raw 缺縣市（甚至缺區）→ 整段補在前面
    return full + raw, True
